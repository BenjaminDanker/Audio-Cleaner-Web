#!/usr/bin/env python3
"""Make the installers download the models during setup.

    python installer_models.py OUT.iss                Windows: Inno Setup include (iscc /DModelsInclude=OUT.iss)
    python installer_models.py --mac SCRIPTS_DIR      macOS: the .pkg's postinstall script (make_pkg.sh)

Generated from the app's own catalog (resources.SPEECH_MODEL, resources.HIGHS_MODEL), so the installer and
the app always agree on URLs, sizes and SHA-256. The installer checks every file's SHA-256 (Inno Setup's
download page does) and installs it into {app}\\models\\<id>\\, where the app looks (models.location). Files
that a previous install already put there with the right size are not downloaded again, so updating the app
does not fetch 2 GB each time. On a Mac the .pkg's postinstall script does the same into
/Library/Application Support/Audio Cleaner/models/<id>/ (models.installer_dir). If a download fails
(offline), setup still finishes; the app then offers the missing download in Settings.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path[:0] = [str(Path(__file__).resolve().parents[1]), str(Path(__file__).resolve().parents[2] / "common")]

from audio_cleaner_desktop import resources  # noqa: E402

CATALOG = (resources.SPEECH_MODEL, resources.HIGHS_MODEL, resources.VOICE_MODEL)


def _pascal(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def render() -> str:
    entries = [(m, f) for m in CATALOG for f in m.files]
    total = sum(f.size for _, f in entries)
    files = []
    adds = []
    for n, (m, f) in enumerate(entries):
        tmp = f"acw-model-{n}"
        rel = Path(f.path)
        dest = "{app}\\models\\" + m.id + ("\\" + str(rel.parent).replace("/", "\\") if str(rel.parent) != "." else "")
        files.append(
            f'Source: "{{tmp}}\\{tmp}"; DestDir: "{dest}"; DestName: "{rel.name}"; '
            "Flags: external skipifsourcedoesntexist ignoreversion"
        )
        adds.append(
            f"  if not ModelFileReady(ExpandConstant({_pascal(dest + chr(92) + rel.name)}), {f.size}) then\n"
            f"  begin\n    ModelDownloads.Add({_pascal(f.url)}, {_pascal(tmp)}, {_pascal(f.sha256)});\n"
            "    Wanted := True;\n  end;"
        )
    return f"""; Generated by desktop/packaging/installer_models.py: do not edit by hand.

[Files]
{chr(10).join(files)}

[Code]
var
  ModelDownloads: TDownloadWizardPage;

function ModelFileReady(const Path: String; Size: Int64): Boolean;
var
  Got: Int64;
begin
  Result := FileSize64(Path, Got) and (Got = Size);
end;

procedure InitializeWizard;
begin
  ModelDownloads := CreateDownloadPage('Downloading Audio Cleaner''s models',
    'The models for subtitles, phone-quality recordings and rebuilding voices ({total / 1e9:.1f} GB, once). '
    + 'After this, everything works offline.', nil);
end;

function NextButtonClick(CurPageID: Integer): Boolean;
var
  Wanted: Boolean;
begin
  Result := True;
  if CurPageID <> wpReady then
    Exit;
  Wanted := False;
  ModelDownloads.Clear;
{chr(10).join(adds)}
  if not Wanted then
    Exit;
  ModelDownloads.Show;
  try
    try
      ModelDownloads.Download;
    except
      SuppressibleMsgBox('Not every model could be downloaded (' + GetExceptionMessage + '). '
        + 'Setup will finish, and Audio Cleaner downloads the rest when it starts.', mbInformation, MB_OK, IDOK);
    end;
  finally
    ModelDownloads.Hide;
  end;
end;
"""


MAC_MODELS = "/Library/Application Support/Audio Cleaner/models"


def render_mac() -> str:
    lines = []
    for m in CATALOG:
        for f in m.files:
            dest = f"{MAC_MODELS}/{m.id}/{f.path}"
            lines.append(f'fetch "{f.url}" "{dest}" {f.size} {f.sha256}')
    total = sum(f.size for m in CATALOG for f in m.files)
    return f"""#!/bin/bash
# postinstall of the Audio Cleaner .pkg: download the models ({total / 1e9:.1f} GB, once).
# Generated by desktop/packaging/installer_models.py: do not edit by hand. Runs as root during setup.
# Every file is checked against its SHA-256 before it is put in place; files already there with the right
# size are kept (updates do not download again). A failed download does not fail the installation: the app
# offers it again in Settings.
LOG=/var/log/audio-cleaner-install.log
failed=0
fetch() {{
  local url="$1" dest="$2" size="$3" sha="$4"
  if [ -f "$dest" ] && [ "$(stat -f%z "$dest")" = "$size" ]; then return 0; fi
  mkdir -p "$(dirname "$dest")"
  local tmp="$dest.download"
  if curl -fL --retry 3 --connect-timeout 30 -o "$tmp" "$url" >>"$LOG" 2>&1 \
     && [ "$(shasum -a 256 "$tmp" | cut -d' ' -f1)" = "$sha" ]; then
    mv -f "$tmp" "$dest"; chmod 644 "$dest"
  else
    rm -f "$tmp"; echo "could not download $url" >>"$LOG"; failed=1
  fi
}}
{chr(10).join(lines)}
chmod -R a+rX "{MAC_MODELS}" 2>/dev/null
[ "$failed" = 0 ] || echo "some models are missing; Audio Cleaner offers them in Settings" >>"$LOG"
exit 0
"""


def main() -> int:
    args = sys.argv[1:]
    if len(args) == 2 and args[0] == "--mac":
        out = Path(args[1])
        out.mkdir(parents=True, exist_ok=True)
        script = out / "postinstall"
        script.write_text(render_mac(), encoding="utf-8")
        script.chmod(0o755)
        return 0
    if len(args) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    Path(args[0]).write_text(render(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
