// Release-time helper (NOT part of `npm run build`): writes licenses-src/rust-crates.txt, the list of Rust
// crates compiled into the DeepFilterNet WebAssembly module with their licences and licence texts.
//
//   node scripts/gen-rust-licenses.mjs
//
// Uses `cargo tree` for the wasm32 target (feature `wasm`, normal dependencies, so it also lists a few
// build-time macro crates: a safe superset) in the checkout that native/deepfilter/build.sh prepares, and
// reads each crate's LICENSE/COPYING/UNLICENSE files from the local cargo registry (so the crates must have
// been downloaded by that build). Re-run it whenever native/deepfilter/Cargo.lock changes, then commit.
//   DFN_BUILD_DIR   default ~/audio-cleaner/src/deepfilter-build
//   CARGO_HOME      default ~/.cargo
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const buildDir = process.env.DFN_BUILD_DIR || join(homedir(), 'audio-cleaner', 'src', 'deepfilter-build');
const cargoHome = process.env.CARGO_HOME || join(homedir(), '.cargo');
const registry = join(cargoHome, 'registry', 'src');
const registryDirs = existsSync(registry) ? readdirSync(registry).map((d) => join(registry, d)) : [];

const tree = execFileSync('cargo', [
  'tree', '--locked', '--offline', '-p', 'deep_filter', '--target', 'wasm32-unknown-unknown',
  '--no-default-features', '--features', 'wasm', '-e', 'normal', '--prefix', 'none', '--format', '{p}|{l}|{r}',
], { cwd: buildDir, encoding: 'utf8', env: { ...process.env, PATH: `${join(cargoHome, 'bin')}:${process.env.PATH}` } });

const crates = new Map();
for (const raw of tree.split('\n')) {
  const line = raw.replace(/ \(\*\)| \(proc-macro\)/g, '').trim();
  if (!line) continue;
  const m = /^(\S+) v(\S+)(?: \([^)]*\))?\|([^|]*)\|(.*)$/.exec(line);
  if (!m) throw new Error(`cannot parse: ${line}`);
  const [, name, version, license, repo] = m;
  if (name === 'deep_filter') continue; // DeepFilterNet itself has its own entry (public/dfn/LICENSE-*)
  crates.set(`${name} ${version}`, { name, version, license: license || 'unspecified', repo });
}

const LICENSE_FILE = /^(licen[sc]e|copying|unlicense)([-_.].*)?$/i;
const norm = (t) => t.replace(/\s+/g, ' ').trim();
const seen = new Map(); // hash -> "crate file" where the text was printed in full
const sections = [];
let noFile = 0;
for (const c of [...crates.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))) {
  const dir = registryDirs.map((d) => join(d, `${c.name}-${c.version}`)).find((d) => existsSync(d));
  const files = dir ? readdirSync(dir).filter((f) => LICENSE_FILE.test(f) && !/\.(rs|toml)$/.test(f)).sort() : [];
  const parts = [`===== ${c.name} ${c.version} =====`, `Licence: ${c.license}`, c.repo ? `Source: ${c.repo}` : null].filter(Boolean);
  if (!files.length) {
    noFile++;
    parts.push('(The published crate contains no separate licence file; it is licensed as stated above.)');
  }
  for (const f of files) {
    const text = readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trimEnd();
    if (text.length < 30) continue;
    const key = createHash('sha256').update(norm(text)).digest('hex');
    if (seen.has(key)) parts.push('', `--- ${f}: identical to ${seen.get(key)} (printed above) ---`);
    else {
      seen.set(key, `${c.name} ${c.version} ${f}`);
      parts.push('', `--- ${f} ---`, text);
    }
  }
  sections.push(parts.join('\n'));
}

const header = `Third-party Rust crates compiled into the DeepFilterNet WebAssembly module (df_bg.wasm)
=========================================================================
${crates.size} crates. Generated by scripts/gen-rust-licenses.mjs from the dependency tree of native/deepfilter/Cargo.lock
(target wasm32-unknown-unknown). The list is a superset: it also contains build-time macro crates.
Where a crate offers several licences (for example "MIT OR Apache-2.0") we use it under either one.
DeepFilterNet itself and tract are listed on the licences page with their own licence texts.

Summary
-------
${[...crates.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version)).map((c) => `${c.name} ${c.version}: ${c.license}`).join('\n')}

Licence texts
-------------
Identical texts are printed once; later crates refer back to the first occurrence.

`;
writeFileSync(join(root, 'licenses-src', 'rust-crates.txt'), `${header}${sections.join('\n\n')}\n`);
console.log(`gen-rust-licenses: ${crates.size} crates, ${seen.size} distinct licence texts, ${noFile} crates without a licence file`);
